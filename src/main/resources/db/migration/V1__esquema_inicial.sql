-- Esquema inicial de EchoStock. SQL portable entre H2 (perfil dev) y PostgreSQL 16.

CREATE TABLE products (
    id              BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    sku             VARCHAR(20)              NOT NULL,
    name            VARCHAR(120)             NOT NULL,
    location_code   VARCHAR(20)              NOT NULL,
    unit            VARCHAR(30)              NOT NULL,
    system_quantity INTEGER                  NOT NULL,
    updated_at      TIMESTAMP WITH TIME ZONE NOT NULL,
    version         BIGINT                   NOT NULL DEFAULT 0,
    CONSTRAINT uk_products_sku UNIQUE (sku),
    CONSTRAINT ck_products_quantity CHECK (system_quantity >= 0)
);

CREATE INDEX ix_products_location_code ON products (location_code);

CREATE TABLE audits (
    id               BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    client_audit_id  VARCHAR(36)              NOT NULL,
    product_id       BIGINT                   NOT NULL,
    sku              VARCHAR(20)              NOT NULL,
    operator_code    VARCHAR(32)              NOT NULL,
    device_id        VARCHAR(64)              NOT NULL,
    system_quantity  INTEGER                  NOT NULL,
    counted_quantity INTEGER                  NOT NULL,
    result           VARCHAR(16)              NOT NULL,
    status           VARCHAR(16)              NOT NULL,
    recorded_at      TIMESTAMP WITH TIME ZONE NOT NULL,
    received_at      TIMESTAMP WITH TIME ZONE NOT NULL,
    reviewed_at      TIMESTAMP WITH TIME ZONE,
    CONSTRAINT uk_audits_client_audit_id UNIQUE (client_audit_id),
    CONSTRAINT fk_audits_product FOREIGN KEY (product_id) REFERENCES products (id),
    CONSTRAINT ck_audits_quantities CHECK (system_quantity >= 0 AND counted_quantity >= 0),
    CONSTRAINT ck_audits_result CHECK (result IN ('MATCH', 'DISCREPANCY')),
    CONSTRAINT ck_audits_status CHECK (status IN ('CONFIRMED', 'PENDING_REVIEW', 'APPROVED', 'REJECTED'))
);

CREATE INDEX ix_audits_sku ON audits (sku);
CREATE INDEX ix_audits_status ON audits (status);
CREATE INDEX ix_audits_recorded_at ON audits (recorded_at);
